function exportTurbulenceProfile(opts)
%EXPORTTURBULENCEPROFILE Bake a von Karman turbulence time history into the firmware.
%   exportTurbulenceProfile()
%   exportTurbulenceProfile(Seed=2, TimeScale_s=1.5)
%
%   Generates ONE position time history (a peak-normalised von Karman
%   turbulence record, the same generator the gust-vane PLC uses) and writes
%   it as HastaDrivers/src/TurbulenceProfile.h, which the board's "random"
%   excitation plays back. Only position is stored. The record is raw
%   (untapered): the firmware windows whatever [startOffsetS, startOffsetS +
%   durationS] slice a test asks for, so different start offsets are
%   different gusts.
%
%   The generator lives in the GustVaneControl repo (not part of this one);
%   GustVaneMatlabDir says where it is. The generated header is committed, so
%   only changing the profile needs that repo. Rebuild and reflash the board
%   after running this.
%
%     GustVaneMatlabDir  folder holding generateVonKarmanTurbulence.m
%     Duration_s         length of the record (default 60)
%     SampleRate_Hz      default 50 (comfortably above the ~15 Hz content)
%     TimeScale_s        von Karman time scale tau (default 2)
%     NumTrials          montecarlo phase trials, keeps the lowest crest factor
%     Seed               RNG seed, so the same profile is reproducible
%     Header             output path (default: HastaDrivers/src/TurbulenceProfile.h)
    arguments
        opts.GustVaneMatlabDir (1,1) string = "C:\git\GustVaneControl\matlab"
        opts.Duration_s (1,1) double {mustBePositive} = 60
        opts.SampleRate_Hz (1,1) double {mustBePositive} = 50
        opts.TimeScale_s (1,1) double {mustBePositive} = 2
        opts.NumTrials (1,1) double {mustBePositive, mustBeInteger} = 10000
        opts.Seed (1,1) double = 1
        opts.Header (1,1) string = ""
    end
    if ~isfile(fullfile(opts.GustVaneMatlabDir, "generateVonKarmanTurbulence.m"))
        error("exportTurbulenceProfile:noGenerator", ...
            "generateVonKarmanTurbulence.m not found in %s - set GustVaneMatlabDir.", opts.GustVaneMatlabDir);
    end
    header = opts.Header;
    if header == ""
        here = fileparts(mfilename("fullpath"));
        header = string(fullfile(here, "..", "..", "..", "HastaDrivers", "src", "TurbulenceProfile.h"));
    end
    oldPath = addpath(char(opts.GustVaneMatlabDir));
    restore = onCleanup(@() path(oldPath));

    [t, pos] = generateVonKarmanTurbulence(opts.Duration_s, SampleRate_Hz=opts.SampleRate_Hz, ...
        TimeScale_s=opts.TimeScale_s, Seed=opts.Seed, PhaseMethod="montecarlo", ...
        NumTrials=opts.NumTrials, ApplyTaper=false);
    n = numel(pos);
    durationS = t(end);
    fprintf("Profile: %d samples at %g Hz (%.2f s), peak %.3f, crest factor %.2f\n", ...
        n, opts.SampleRate_Hz, durationS, max(abs(pos)), max(abs(pos)) / rms(pos));

    fid = fopen(header, "w");
    if fid < 0
        error("exportTurbulenceProfile:writeFailed", "Could not open %s for writing.", header);
    end
    closer = onCleanup(@() fclose(fid));
    fprintf(fid, "#pragma once\n");
    fprintf(fid, "// GENERATED by matlab/hastadaq/tools/exportTurbulenceProfile.m on %s - do not edit.\n", ...
        char(datetime("now", Format="yyyy-MM-dd HH:mm")));
    fprintf(fid, "// One von Karman turbulence POSITION record (peak-normalised to 1, raw/untapered), seed %d,\n", opts.Seed);
    fprintf(fid, "// time scale %g s, montecarlo phasing. Played back by ExcitationGenerator's RANDOM type.\n", opts.TimeScale_s);
    fprintf(fid, "namespace TurbulenceProfile {\n");
    fprintf(fid, "constexpr int kSamples = %d;\n", n);
    fprintf(fid, "constexpr float kRateHz = %.6ff;\n", opts.SampleRate_Hz);
    fprintf(fid, "constexpr float kDurationS = %.6ff;   // (kSamples-1)/kRateHz, the time of the last sample\n", durationS);
    fprintf(fid, "inline constexpr float kPosition[kSamples] = {\n");
    for i = 1:10:n
        last = min(i + 9, n);
        vals = strjoin(compose("%.6ff", pos(i:last).'), ", ");
        if last < n
            fprintf(fid, "    %s,\n", vals);
        else
            fprintf(fid, "    %s\n", vals);
        end
    end
    fprintf(fid, "};\n}  // namespace TurbulenceProfile\n");
    fprintf("Wrote %s\n", header);
end
